w("- ERC ในโมเดลคือฐานล้วน (ไม่มีการเอียงตามคะแนน 0.6–1.4×) · ภาษีปันผล 15% ไม่ถูกหัก · โมเดลไม่มีทศวรรษ 1970 · เหตุการณ์ส่วนใหญ่เป็นข้อสมมติของผม")
w("- `boot` คือโลกเดียวที่ไม่พึ่งข้อสมมติเหตุการณ์ แต่ใช้ประวัติจริงแค่ 22 ปีที่หุ้นสหรัฐและทองดีผิดปกติ จึงเป็นขอบบนที่ไม่ควรเชื่อ")
w("- CF ในโลกจริงใช้กับพอร์ตที่ผู้ใช้ถืออยู่แล้ว (เงินใหม่ต่อมูลค่ารวมต่างจากเริ่มจากศูนย์) การจำลองนี้เริ่มจากศูนย์เท่ากันทุกสูตรเพื่อเทียบกันได้")
