diag = json.load(open(R / "new_diag_events.json")) if (R / "new_diag_events.json").exists() else None

NAME = {"ERC": "ERC (ผู้ครองตำแหน่ง)", "CF_ERC": "CF_ERC (เป้า ERC + เติมเงินเข้ากองที่ต่ำกว่าเป้า)",
        "CF_EQ": "CF_EQ (เป้า 1/N + เติมเงินเข้ากองที่ต่ำกว่าเป้า)", "BLEND": "BLEND (ERC ครึ่ง / 1/N ครึ่ง)",
        "EQ": "1/N", "DAR": "DAR", "PRESET": "35/25/20/10/10", "VOO": "VOO ล้วน"}
